#include<iostream>
using namespace std;

///////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Function Name : DisplayFactors
//  Description :   Used to display factors of 6
//  Input :         None
//  Output :        None
//  Author :        Shreya Pramod Pasalkar
///////////////////////////////////////////////////////////////////////////////////////////////////////////////
void DisplayFactors()
{
    if(6 % 1 == 0)
    {
        cout<<"1\t";
    }
    if(6 % 2 == 0)
    {
        cout<<"2\t";
    }
    if(6 % 3 == 0)
    {
        cout<<"3\t";
    }
    if(6 % 4 == 0)
    {
        cout<<"4\t";
    }
    if(6 % 5 == 0)
    {
        cout<<"5\t";
    }

    cout<<"\n";
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Entry-point Function
///////////////////////////////////////////////////////////////////////////////////////////////////////////////
int main()
{
    DisplayFactors();

    return 0;
}

