#include<iostream>
using namespace std;

///////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Function Name : DisplayFactors
//  Description :   Used to display factors of iNo
//  Input :         Integer
//  Output :        None
//  Author :        Shreya Pramod Pasalkar
///////////////////////////////////////////////////////////////////////////////////////////////////////////////
void DisplayFactors(int iNo)
{
    if(iNo % 1 == 0)
    {
        cout<<"1\t";
    }
    if(iNo % 2 == 0)
    {
        cout<<"2\t";
    }
    if(iNo % 3 == 0)
    {
        cout<<"3\t";
    }
    if(iNo % 4 == 0)
    {
        cout<<"4\t";
    }
    if(iNo % 5 == 0)
    {
        cout<<"5\t";
    }

    cout<<"\n";
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Entry-point Function
///////////////////////////////////////////////////////////////////////////////////////////////////////////////
int main()
{
    int iNo = 6;

    DisplayFactors(iNo);

    return 0;
}

