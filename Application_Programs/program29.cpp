#include<iostream>
using namespace std;

///////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Function Name : DisplayNumbers
//  Description :   Used to display numbers in reverse order
//  Pattern :       5   4   3   2   1
//  Input :         nothing
//  Output :        void
//  Date :          06/10/26
//  Author :        Shreya Pramod Pasalkar
///////////////////////////////////////////////////////////////////////////////////////////////////////////////
void DisplayReverse()
{
    // Static
    cout<<"5\t";
    cout<<"4\t";
    cout<<"3\t";
    cout<<"2\t";
    cout<<"1\t";
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Entry-point Function
///////////////////////////////////////////////////////////////////////////////////////////////////////////////
int main()
{
    DisplayReverse();

    return 0;
}

