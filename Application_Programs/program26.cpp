#include<iostream>
using namespace std;

///////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Function Name : DisplayNumbers
//  Description :   Used to display * in a line
//  Pattern :       *   *   *   *   *
//  Input :         nothing
//  Output :        void
//  Date :          06/10/26
//  Author :        Shreya Pramod Pasalkar
///////////////////////////////////////////////////////////////////////////////////////////////////////////////
void Display()
{
    // Loop Counter
    int iCnt = 0;

    // Iteration - for loop
    for(iCnt = 1; iCnt <= 5; iCnt++)
    {
        cout<<"*\t";
    }

    cout<<"\n";
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Entry-point Function
///////////////////////////////////////////////////////////////////////////////////////////////////////////////
int main()
{
    Display();

    return 0;
}

